create or replace function public.log_portal_change()
returns trigger language plpgsql security definer set search_path=public as $$
declare p jsonb; label text; actor_name text; actor_mobile text; actor_email text; rid text;
begin
 p:=case when TG_OP='DELETE' then to_jsonb(OLD) else to_jsonb(NEW) end;
 rid:=coalesce(p->>'id',p->>'register_no',p->>'report_no',p->>'part_no','?');
 label:=coalesce(p->>'drawing_no',p->>'report_no',p->>'part_no',p->>'register_no',rid);
 select employee_name,mobile_no,official_email into actor_name,actor_mobile,actor_email from public.user_profiles where id=auth.uid();
 insert into public.portal_audit_log(module,record_id,action,actor_id,actor_name,actor_mobile,actor_email,record_label,old_data,new_data)
 values(TG_ARGV[0],rid,TG_OP,auth.uid(),actor_name,actor_mobile,actor_email,label,
 case when TG_OP in('UPDATE','DELETE') then to_jsonb(OLD) else null end,
 case when TG_OP in('INSERT','UPDATE') then to_jsonb(NEW) else null end);
 return coalesce(NEW,OLD);
end; $$;

