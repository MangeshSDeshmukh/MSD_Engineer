-- Mutha Quality Portal: Access Control + WLS + Plant-wise Master Part List + Audit Log
-- Run ONCE in Supabase SQL Editor. Existing Engineering Drawing records are preserved.

create table if not exists public.user_module_permissions (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 module text not null check (module in ('engineering_drawing','wls','master_part')),
 can_view boolean not null default false,
 can_add boolean not null default false,
 can_edit boolean not null default false,
 updated_at timestamptz not null default now(),
 unique(user_id,module)
);

create table if not exists public.master_part_list (
 id bigint generated by default as identity primary key,
 plant_unit text not null,
 customer_name text,
 part_no text not null,
 part_name text not null,
 drawing_no text,
 revision text,
 part_type text,
 material text,
 process text,
 model text,
 status text default 'Active',
 remarks text,
 created_by uuid references auth.users(id),
 updated_by uuid references auth.users(id),
 created_at timestamptz default now(),
 updated_at timestamptz default now()
);

create table if not exists public.portal_audit_log (
 id bigint generated by default as identity primary key,
 module text not null,
 record_id text not null,
 action text not null check (action in ('INSERT','UPDATE','DELETE')),
 actor_id uuid references auth.users(id),
 actor_name text,
 actor_mobile text,
 actor_email text,
 record_label text,
 old_data jsonb,
 new_data jsonb,
 created_at timestamptz default now()
);

create table if not exists public.whatsapp_notifications (
 id bigint generated by default as identity primary key,
 audit_id bigint references public.portal_audit_log(id) on delete cascade,
 recipient_user_id uuid references auth.users(id) on delete set null,
 recipient_name text,
 recipient_mobile text,
 message text not null,
 status text default 'Pending',
 sent_at timestamptz,
 created_at timestamptz default now()
);

create or replace function public.is_portal_admin()
returns boolean language sql security definer set search_path=public as $$
 select exists(select 1 from public.user_profiles
 where id=auth.uid() and approval_status='Approved' and role='Admin');
$$;

create or replace function public.has_module_access(p_module text,p_action text)
returns boolean language plpgsql security definer set search_path=public as $$
declare ok boolean;
begin
 if public.is_portal_admin() then return true; end if;
 select case p_action when 'view' then can_view when 'add' then can_add when 'edit' then can_edit else false end
 into ok from public.user_module_permissions
 where user_id=auth.uid() and module=p_module;
 return coalesce(ok,false);
end; $$;

